# 20.x.1 — separate η_c / η_d identification from SOC-trace telemetry
# ---------------------------------------------------------------------------

def solve_site_split(theta, demand=DEMAND):
    # soc_init=0 forces the battery to CHARGE before it can discharge, so
    # both efficiencies are exercised in the telemetry window.
    prob = StorageDispatchProblem(
        marginal_cost=np.array([10.0, 60.0]), capacity=np.array([80.0, 80.0]),
        demand=np.asarray(demand, dtype=float),
        charge_eff=float(theta["eta_c"]), discharge_eff=float(theta["eta_d"]),
        power_limit=40.0, soc_max=200.0, soc_init=0.0, ridge=RIDGE)
    return solve_storage_dispatch_with_sensitivities(prob)


def test_eta_split_unidentifiable_from_dispatch_alone():
    """Sanity for the deferral rationale: dispatch-only residual leaves the
    (η_c, η_d) split ill-determined — the fit may land on a different point
    with (near-)matching dispatch, or the gate may freeze a direction."""
    demand = np.array([30.0, 30.0, 95.0, 90.0])
    true = {"eta_c": 0.97, "eta_d": 0.90}
    obs = solve_site_split(true, demand=demand).dispatch
    rep = fit_params(
        lambda th: solve_site_split(th, demand=demand), obs,
        {"eta_c": (0.80, 0.5, 1.0), "eta_d": (0.80, 0.5, 1.0)},
        lambda s, th: np.column_stack(
            [s.d_dispatch_d_charge_eff, s.d_dispatch_d_discharge_eff]),
        n_iter=60)
    # Dispatch may be matched well...
    assert rep.loss_history[-1] < 1e-6
    # ...but we don't assert the individual etas: only their effect is pinned.


def test_eta_split_recovered_with_soc_trace():
    """With SOC in the residual, η_c and η_d are SEPARATELY identifiable."""
    demand = np.array([30.0, 30.0, 95.0, 90.0])
    true = {"eta_c": 0.97, "eta_d": 0.90}
    sol_true = solve_site_split(true, demand=demand)
    assert sol_true.charge.max() > 1.0 and sol_true.discharge.max() > 1.0
    obs = np.concatenate([sol_true.dispatch.reshape(-1), sol_true.soc])

    def residual(sol):
        return np.concatenate(
            [sol.dispatch.reshape(-1), sol.soc]) - obs

    def jacobian(sol, theta):
        col_c = np.concatenate(
            [sol.d_dispatch_d_charge_eff, sol.d_soc_d_charge_eff])
        col_d = np.concatenate(
            [sol.d_dispatch_d_discharge_eff, sol.d_soc_d_discharge_eff])
        return np.column_stack([col_c, col_d])

    rep = fit_params(
        lambda th: solve_site_split(th, demand=demand),
        obs,
        {"eta_c": (0.80, 0.5, 1.0), "eta_d": (0.80, 0.5, 1.0)},
        jacobian,
        residual_fn=residual,
        n_iter=60)
    print(f"\n[eta-split] recovered eta_c={rep.params_new['eta_c']:.5f} "
          f"(true 0.97), eta_d={rep.params_new['eta_d']:.5f} (true 0.90); "
          f"{rep.n_solves} solves")
    assert abs(rep.params_new["eta_c"] - 0.97) < 1e-3
    assert abs(rep.params_new["eta_d"] - 0.90) < 1e-3


