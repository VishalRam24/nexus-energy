def _make_cal(**kw):
    return AutoCalibrator(
        solution_factory=lambda w, th: solve_site(th, demand=w["demand"]),
        jacobian_fn=jac,
        observed_fn=lambda w: w["observed"],
        params={"mc_peaker": (85.0, 20.0, 150.0), "eta_d": (0.70, 0.5, 1.0)},
        n_iter_per_cycle=10, **kw)


def _window():
    observed = solve_site(TRUE).dispatch
    return {"demand": DEMAND, "observed": observed}


def test_disable_enable_toggle():
    cal = _make_cal()
    cal.disable()
    assert cal.step(_window()) is None
    assert cal.believed == {"mc_peaker": 85.0, "eta_d": 0.70}  # untouched
    cal.enable()
    rep = cal.step(_window())
    assert rep is not None
    assert abs(cal.believed["eta_d"] - 0.70) > 1e-3  # moved once enabled


def test_lock_param_holds_value_while_others_fit():
    cal = _make_cal(max_rel_step=1.0)
    cal.lock_param("eta_d")
    rep = cal.step(_window())
    assert rep.params_new["eta_d"] == 0.70          # held exactly
    assert rep.frozen["eta_d"] is True               # reported as held
    assert abs(rep.params_new["mc_peaker"] - 60.0) < 1.0  # others still fit
    cal.unlock_param("eta_d")
    cal.step(_window())
    assert abs(cal.believed["eta_d"] - 0.70) > 1e-3  # free again


def test_set_param_manual_override_and_lock():
    cal = _make_cal()
    cal.set_param("eta_d", 0.93, lock=True)
    assert cal.believed["eta_d"] == 0.93
    cal.step(_window())
    assert cal.believed["eta_d"] == 0.93             # locked against auto-fit
    cal.set_param("eta_d", 2.0)                      # clamped to box
    assert cal.believed["eta_d"] == 1.0
    with pytest.raises(KeyError):
        cal.set_param("nope", 1.0)


def test_all_locked_skips_fit():
    cal = _make_cal()
    cal.lock_param("eta_d")
    cal.lock_param("mc_peaker")
    assert cal.step(_window()) is None


