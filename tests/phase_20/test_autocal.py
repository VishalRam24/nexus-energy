"""N_En_Phase 20 — auto-calibration driver tests.

Fixture: the single-bus storage site from the diff layer (2 gens +
battery). Parameters under calibration: the peaker's marginal cost and
the battery's discharge efficiency (the new η Jacobian block). Telemetry
is generated by the TRUE model; beliefs start wrong.
"""

from __future__ import annotations

import numpy as np
import pytest

from nexus_energy.autocal import AutoCalibrator, CalibrationReport, fit_params
from nexus_energy.diff import (
    StorageDispatchProblem,
    solve_storage_dispatch_with_sensitivities,
)

RIDGE = 1.0
DEMAND = np.array([60.0, 75.0, 95.0, 70.0])


def solve_site(theta, demand=DEMAND, extra_gen_mc=None):
    mc = [10.0, float(theta["mc_peaker"])]
    cap = [80.0, 80.0]
    if extra_gen_mc is not None:
        mc.append(extra_gen_mc)
        cap.append(50.0)
    prob = StorageDispatchProblem(
        marginal_cost=np.asarray(mc), capacity=np.asarray(cap),
        demand=np.asarray(demand, dtype=float),
        charge_eff=0.95, discharge_eff=float(theta["eta_d"]),
        power_limit=40.0, soc_max=200.0, soc_init=60.0, ridge=RIDGE)
    return solve_storage_dispatch_with_sensitivities(prob)


def jac(sol, theta, *, n_extra=0):
    cols = [
        sol.d_dispatch_d_mc[:, 1],            # ∂dispatch/∂mc_peaker
        sol.d_dispatch_d_discharge_eff,       # ∂dispatch/∂η_d
    ]
    for j in range(n_extra):
        cols.append(sol.d_dispatch_d_mc[:, 2 + j])
    return np.column_stack(cols)


TRUE = {"mc_peaker": 60.0, "eta_d": 0.95}


def test_two_param_recovery():
    observed = solve_site(TRUE).dispatch
    report = fit_params(
        lambda th: solve_site(th),
        observed,
        {"mc_peaker": (85.0, 20.0, 150.0), "eta_d": (0.70, 0.5, 1.0)},
        jac,
        n_iter=40,
    )
    print(f"\n[autocal] recovered {report.params_new} in "
          f"{report.n_solves} solves; loss {report.loss_history[-1]:.3e}")
    assert abs(report.params_new["mc_peaker"] - 60.0) < 1e-3 * 60.0
    assert abs(report.params_new["eta_d"] - 0.95) < 1e-3
    assert report.loss_history[-1] < 1e-10
    # Loss decreased monotonically over accepted steps.
    assert all(b <= a + 1e-12 for a, b in
               zip(report.loss_history, report.loss_history[1:]))


def test_gate_freezes_data_silent_param():
    # A third generator priced out of the market: its dispatch is pinned
    # at 0 in every period → its mc column is exactly zero → data-silent.
    observed = solve_site(TRUE, extra_gen_mc=500.0).dispatch
    report = fit_params(
        lambda th: solve_site(th, extra_gen_mc=float(th["mc_ghost"])),
        observed,
        {"mc_peaker": (75.0, 20.0, 150.0), "eta_d": (0.80, 0.5, 1.0),
         "mc_ghost": (500.0, 300.0, 900.0)},
        lambda s, th: jac(s, th, n_extra=1),
        n_iter=40,
    )
    assert report.frozen["mc_ghost"] is True
    assert report.params_new["mc_ghost"] == 500.0  # untouched
    assert abs(report.params_new["mc_peaker"] - 60.0) < 1e-2 * 60.0


def test_box_clipping():
    observed = solve_site(TRUE).dispatch
    # True eta_d (0.95) lies OUTSIDE the box → fit lands on the bound.
    report = fit_params(
        lambda th: solve_site(th),
        observed,
        {"mc_peaker": (60.0, 20.0, 150.0), "eta_d": (0.70, 0.5, 0.85)},
        jac,
        n_iter=40,
    )
    assert report.params_new["eta_d"] == pytest.approx(0.85, abs=1e-9)


def test_max_rel_step_limits_slew():
    observed = solve_site(TRUE).dispatch
    report = fit_params(
        lambda th: solve_site(th),
        observed,
        {"mc_peaker": (120.0, 20.0, 150.0), "eta_d": (0.60, 0.5, 1.0)},
        jac,
        n_iter=1,
        max_rel_step=0.25,
    )
    assert abs(report.params_new["mc_peaker"] - 120.0) <= 0.25 * 120.0 + 1e-9
    assert abs(report.params_new["eta_d"] - 0.60) <= 0.25 * 0.60 + 1e-9


def test_autocalibrator_tracks_drift():
    # True η_d degrades linearly 0.95 → 0.85 over 10 windows; the
    # calibrator (seeded right once) follows within its slew limit.
    cal = AutoCalibrator(
        solution_factory=lambda window, th: solve_site(th, demand=window["demand"]),
        jacobian_fn=jac,
        observed_fn=lambda window: window["observed"],
        params={"mc_peaker": (60.0, 20.0, 150.0), "eta_d": (0.95, 0.5, 1.0)},
        update_every=2,
        n_iter_per_cycle=8,
        max_rel_step=0.25,
    )
    rng = np.random.default_rng(5)
    errs = []
    for k in range(10):
        true_eta = 0.95 - 0.01 * (k + 1)
        demand = DEMAND + rng.normal(0, 2, DEMAND.size)
        observed = solve_site({"mc_peaker": 60.0, "eta_d": true_eta},
                              demand=demand).dispatch
        rep = cal.step({"demand": demand, "observed": observed})
        if k % 2 == 0:
            assert isinstance(rep, CalibrationReport)
        else:
            assert rep is None  # skipped cycle (update_every=2)
        errs.append(abs(cal.believed["eta_d"] - true_eta))
    print(f"\n[autocal-drift] final believed eta_d={cal.believed['eta_d']:.4f} "
          f"true=0.85; per-window |err|={[round(e, 4) for e in errs]}")
    # Tracks the drift closely by the end.
    assert errs[-1] < 0.02


