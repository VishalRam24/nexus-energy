# 20.x.2 — noise-aware MHE (smoothing + outlier rejection)
# ---------------------------------------------------------------------------

def test_noise_smoothing_beats_raw_fits():
    """With noisy telemetry, EMA-smoothed beliefs track the constant true
    value with LOWER error spread than per-window raw fits."""
    rng = np.random.default_rng(9)
    true = {"mc_peaker": 60.0, "eta_d": 0.95}

    def windows(n):
        for _ in range(n):
            demand = DEMAND + rng.normal(0, 2, DEMAND.size)
            obs = solve_site(true, demand=demand).dispatch \
                + rng.normal(0, 1.5, (2, DEMAND.size))
            yield {"demand": demand, "observed": obs}

    def run(smooth):
        cal = AutoCalibrator(
            solution_factory=lambda w, th: solve_site(th, demand=w["demand"]),
            jacobian_fn=jac, observed_fn=lambda w: w["observed"],
            params={"mc_peaker": (60.0, 20.0, 150.0),
                    "eta_d": (0.90, 0.5, 1.0)},
            n_iter_per_cycle=6, max_rel_step=0.5,
            noise_std=1.5, smooth=smooth)
        ests = []
        for w in windows(15):
            cal.step(w)
            ests.append(cal.believed["eta_d"])
        return np.array(ests)

    rng = np.random.default_rng(9)
    raw = run(smooth=1.0)
    rng = np.random.default_rng(9)
    smoothed = run(smooth=0.3)
    err_raw = np.abs(raw[5:] - 0.95)
    err_smooth = np.abs(smoothed[5:] - 0.95)
    print(f"\n[mhe] mean |err| raw={err_raw.mean():.4f} "
          f"smoothed={err_smooth.mean():.4f}")
    assert err_smooth.mean() <= err_raw.mean() + 1e-6
    assert err_smooth.mean() < 0.02


def test_outlier_window_rejected():
    cal = AutoCalibrator(
        solution_factory=lambda w, th: solve_site(th, demand=w["demand"]),
        jacobian_fn=jac, observed_fn=lambda w: w["observed"],
        params={"mc_peaker": (60.0, 20.0, 150.0), "eta_d": (0.95, 0.5, 1.0)},
        n_iter_per_cycle=6, noise_std=1.5, smooth=0.5)
    garbage = {"demand": DEMAND,
               "observed": np.full((2, DEMAND.size), 500.0)}  # sensor fault
    rep = cal.step(garbage)
    assert "REJECTED" in rep.message
    assert cal.believed == {"mc_peaker": 60.0, "eta_d": 0.95}  # untouched
